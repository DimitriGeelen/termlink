//! Founding-verb use log and owner-only sessions (T-3702, arc-011 P-14 / B-4, 06a AL-32, 04 6.6.4).
//!
//! The founding verbs `command.inject` (`termlink inject`, `pty inject`) and
//! `command.execute` (`exec`, `remote exec`) stay open by design (R-4, RR-13).
//! What this module adds is that every call is SEEN and that a session may
//! refuse callers other than its owner:
//!
//! 1. A use-log row for every call, allowed or refused, written BEFORE the verb
//!    acts. If the row cannot be written the verb is refused (FCW-132): a call
//!    that cannot be seen does not happen.
//! 2. The scope check as built (`inject` needs `control`, `execute` needs
//!    `execute`; FCW-130), now recorded in the row.
//! 3. Owner-only: a session started with `TERMLINK_OWNER_ONLY=<owner>` refuses a
//!    founding verb from any caller whose declared identity (`params.from`) is
//!    not the owner, including a caller that declares none (FCW-131).
//!    `TERMLINK_OWNER_ONLY_CHECK=0` turns the check off (the rollback); the log
//!    stays on regardless.
//!
//! The same row builder and writer serve the hub (`termlink-hub` writes its own
//! row, with the hub's view of the caller, before relaying the call).
//!
//! Identity is DECLARED, not proven: `params.from` is what the caller says it is.
//! Proof of identity is the agent key card (B-6) and the PH-4 boundary model
//! (RA-2); until then owner-only stops accidental and naive cross-agent use and
//! every attempt is on record with the caller's uid/pid or peer address.
use std::path::{Path, PathBuf};

use termlink_protocol::control;
use termlink_protocol::jsonrpc::{ErrorResponse, RpcResponse};

use crate::auth::{self, PermissionScope};

/// The founding verbs, as RPC methods (pty inject is `command.inject`; remote
/// exec is `command.execute` relayed by the hub).
pub const FOUNDING_VERBS: &[&str] = &[
    control::method::COMMAND_INJECT,
    control::method::COMMAND_EXECUTE,
];

/// Owner identity for owner-only sessions, read once at session start.
pub const OWNER_ONLY_ENV: &str = "TERMLINK_OWNER_ONLY";
/// `0` / `false` / `off` turns the owner-only check off (rollback; the log stays).
pub const OWNER_ONLY_CHECK_ENV: &str = "TERMLINK_OWNER_ONLY_CHECK";
/// Override for the session's use-log path.
pub const USE_LOG_PATH_ENV: &str = "TERMLINK_USE_LOG";
/// The use log rotates one generation (`.1`) past this size.
pub const USE_LOG_MAX_BYTES: u64 = 16 * 1024 * 1024;

pub fn is_founding_verb(method: &str) -> bool {
    FOUNDING_VERBS.contains(&method)
}

/// What a session does about founding verbs. Set at session start, never changed.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Policy {
    /// `Some(owner)` → the session is owner-only.
    pub owner_only: Option<String>,
    /// `false` → the owner-only check is off (rollback). The log is unaffected.
    pub check_owner: bool,
    /// `None` → resolved per call as `<socket dir>/use-log/<session_id>.jsonl`
    /// (the sessions dir, so a test's temp sessions dir keeps its rows), or
    /// `<runtime_dir>/use-log/` for a session with no Unix socket.
    pub log_path: Option<PathBuf>,
}

impl Policy {
    /// The policy from an environment lookup (pure: tests pass a closure).
    pub fn from_lookup(get: impl Fn(&str) -> Option<String>) -> Self {
        let owner_only = get(OWNER_ONLY_ENV)
            .map(|s| s.trim().to_string())
            .filter(|s| !s.is_empty());
        let check_owner = !matches!(
            get(OWNER_ONLY_CHECK_ENV).map(|s| s.trim().to_ascii_lowercase()).as_deref(),
            Some("0") | Some("false") | Some("off") | Some("no")
        );
        let log_path = get(USE_LOG_PATH_ENV)
            .map(|s| s.trim().to_string())
            .filter(|s| !s.is_empty())
            .map(PathBuf::from);
        Self { owner_only, check_owner, log_path }
    }

    pub fn from_env() -> Self {
        Self::from_lookup(|k| std::env::var(k).ok())
    }

    /// Where this session's rows go.
    pub fn resolve_log_path(&self, session_id: &str, socket_dir: Option<&Path>) -> PathBuf {
        if let Some(p) = &self.log_path {
            return p.clone();
        }
        match socket_dir {
            Some(d) => default_log_path(d, session_id),
            None => default_log_path(&crate::discovery::runtime_dir(), session_id),
        }
    }
}

pub fn default_log_path(base_dir: &Path, session_id: &str) -> PathBuf {
    // A session id is generated by us (`tl-...`), but keep the file name safe anyway.
    let safe: String = session_id
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() || c == '-' || c == '_' { c } else { '_' })
        .collect();
    base_dir.join("use-log").join(format!("{safe}.jsonl"))
}

/// The outcome of the checks, decided before the row is written so the row
/// records it; the row is still written before anything acts.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Decision {
    Allowed,
    /// FCW-130: the connection's scope is below what the verb needs.
    RefusedScope { required: PermissionScope, granted: PermissionScope },
    /// FCW-131: owner-only session, caller is not the owner.
    RefusedOwner { owner: String, caller: Option<String> },
}

impl Decision {
    pub fn label(&self) -> &'static str {
        match self {
            Decision::Allowed => "allowed",
            Decision::RefusedScope { .. } => "refused-scope",
            Decision::RefusedOwner { .. } => "refused-owner",
        }
    }
    pub fn fcw(&self) -> Option<&'static str> {
        match self {
            Decision::Allowed => None,
            Decision::RefusedScope { .. } => Some("FCW-130"),
            Decision::RefusedOwner { .. } => Some("FCW-131"),
        }
    }
}

/// Pure: scope first (FCW-130), then owner-only (FCW-131).
pub fn decide(method: &str, granted: PermissionScope, caller_from: Option<&str>, policy: &Policy) -> Decision {
    let required = auth::method_scope(method);
    if !granted.satisfies(required) {
        return Decision::RefusedScope { required, granted };
    }
    if policy.check_owner
        && let Some(owner) = &policy.owner_only
        && caller_from != Some(owner.as_str())
    {
        return Decision::RefusedOwner { owner: owner.clone(), caller: caller_from.map(str::to_string) };
    }
    Decision::Allowed
}

/// Pure: one use-log row. `at` is `"session"` or `"hub"`; `caller` is that
/// side's view of who called (declared `from` plus uid/pid or peer address).
pub fn build_row(
    ts_ms: u64,
    at: &str,
    method: &str,
    target: Option<&str>,
    caller: serde_json::Value,
    granted: Option<PermissionScope>,
    decision: &Decision,
) -> serde_json::Value {
    let mut row = serde_json::json!({
        "ts": ts_ms,
        "founding": true,
        "at": at,
        "verb": method,
        "caller": caller,
        "scope": granted.map(|s| s.to_string()),
        "decision": decision.label(),
    });
    if let Some(t) = target {
        row["target"] = serde_json::Value::from(t);
    }
    if let Some(f) = decision.fcw() {
        row["fcw"] = serde_json::Value::from(f);
    }
    row
}

/// Append one row: parent dir created, the line is ONE `O_APPEND` write (shared
/// capped writer, one rotated generation). `Err` → the caller refuses the verb.
pub fn append_row(path: &Path, row: &serde_json::Value) -> std::io::Result<()> {
    if let Some(dir) = path.parent()
        && !dir.as_os_str().is_empty()
    {
        std::fs::create_dir_all(dir)?;
    }
    crate::audit_append::append_line_capped(path, &row.to_string(), USE_LOG_MAX_BYTES)
}

pub fn now_ms() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_millis() as u64)
        .unwrap_or(0)
}

/// The refusal for a decision that is not `Allowed`.
pub fn refusal(id: serde_json::Value, method: &str, decision: &Decision) -> Option<RpcResponse> {
    match decision {
        Decision::Allowed => None,
        Decision::RefusedScope { required, granted } => Some(
            ErrorResponse::with_data(
                id,
                control::error_code::AUTH_DENIED,
                &format!(
                    "Permission denied: method '{method}' requires '{required}' scope, connection has '{granted}'"
                ),
                serde_json::json!({"fcw": "FCW-130", "required": required.to_string(), "granted": granted.to_string()}),
            )
            .into(),
        ),
        Decision::RefusedOwner { owner, caller } => Some(
            ErrorResponse::with_data(
                id,
                control::error_code::AUTH_DENIED,
                &format!(
                    "refused: this session is owner-only (owner '{owner}') and '{method}' came from {}; \
                     the call is logged (FCW-131)",
                    caller.as_deref().map(|c| format!("'{c}'")).unwrap_or_else(|| "an undeclared caller (no 'from')".into())
                ),
                serde_json::json!({"fcw": "FCW-131", "owner": owner, "caller": caller}),
            )
            .into(),
        ),
    }
}

/// The refusal when the row could not be written (FCW-132).
pub fn log_unwritable(id: serde_json::Value, method: &str, err: &std::io::Error) -> RpcResponse {
    ErrorResponse::with_data(
        id,
        control::error_code::USE_LOG_UNWRITABLE,
        &format!(
            "refused: '{method}' is a founding verb and its use-log row could not be written ({err}); \
             nothing was done (FCW-132)"
        ),
        serde_json::json!({"fcw": "FCW-132"}),
    )
    .into()
}

/// Session side, all three steps: decide, write the row, refuse or let through.
/// `None` → the verb may act; `Some(resp)` → send `resp`, do not act.
#[allow(clippy::too_many_arguments)]
pub fn gate_session(
    id: serde_json::Value,
    method: &str,
    params: &serde_json::Value,
    granted: PermissionScope,
    peer: (Option<u32>, Option<u32>),
    session_id: &str,
    socket_dir: Option<&Path>,
    policy: &Policy,
) -> Option<RpcResponse> {
    let from = params.get("from").and_then(|v| v.as_str());
    let decision = decide(method, granted, from, policy);
    let caller = serde_json::json!({"from": from, "uid": peer.0, "pid": peer.1});
    let row = build_row(now_ms(), "session", method, Some(session_id), caller, Some(granted), &decision);
    let path = policy.resolve_log_path(session_id, socket_dir);
    if let Err(e) = append_row(&path, &row) {
        tracing::error!(method, path = %path.display(), error = %e, "T-3702: founding verb refused, use-log row not written (FCW-132)");
        return Some(log_unwritable(id, method, &e));
    }
    if decision != Decision::Allowed {
        tracing::warn!(method, decision = decision.label(), "T-3702: founding verb refused");
    }
    refusal(id, method, &decision)
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn policy(owner: Option<&str>, path: PathBuf) -> Policy {
        Policy { owner_only: owner.map(str::to_string), check_owner: true, log_path: Some(path) }
    }

    fn rows(path: &Path) -> Vec<serde_json::Value> {
        std::fs::read_to_string(path)
            .unwrap_or_default()
            .lines()
            .map(|l| serde_json::from_str(l).unwrap())
            .collect()
    }

    #[test]
    fn founding_verbs_are_inject_and_execute_only() {
        assert!(is_founding_verb("command.inject"));
        assert!(is_founding_verb("command.execute"));
        assert!(!is_founding_verb("command.signal"));
        assert!(!is_founding_verb("query.output"));
    }

    #[test]
    fn policy_from_env_lookup() {
        let p = Policy::from_lookup(|_| None);
        assert_eq!(p, Policy { owner_only: None, check_owner: true, log_path: None });
        let p = Policy::from_lookup(|k| match k {
            OWNER_ONLY_ENV => Some(" agent-a ".into()),
            OWNER_ONLY_CHECK_ENV => Some("0".into()),
            _ => None,
        });
        assert_eq!(p.owner_only.as_deref(), Some("agent-a"));
        assert!(!p.check_owner, "TERMLINK_OWNER_ONLY_CHECK=0 is the rollback");
        let p = Policy::from_lookup(|k| (k == OWNER_ONLY_ENV).then(|| "  ".into()));
        assert_eq!(p.owner_only, None, "blank owner is not owner-only");
    }

    #[test]
    fn default_path_is_under_runtime_dir_and_sanitised() {
        let p = default_log_path(Path::new("/r"), "tl-ab/../c");
        assert_eq!(p, PathBuf::from("/r/use-log/tl-ab____c.jsonl"));
    }

    // E-68: scopes. observe and notify refused for both verbs; control may inject
    // but not execute; execute may both.
    #[test]
    fn e68_scope_matrix() {
        let p = Policy::default();
        use PermissionScope::*;
        for (scope, inject_ok, exec_ok) in [
            (Observe, false, false),
            (Notify, false, false),
            (Interact, false, false),
            (Control, true, false),
            (Execute, true, true),
        ] {
            assert_eq!(decide("command.inject", scope, None, &p) == Decision::Allowed, inject_ok, "inject with {scope}");
            assert_eq!(decide("command.execute", scope, None, &p) == Decision::Allowed, exec_ok, "execute with {scope}");
        }
    }

    // E-68: owner-only refuses another identity and an undeclared caller; the owner passes.
    #[test]
    fn e68_owner_only() {
        let p = policy(Some("agent-a"), PathBuf::new());
        assert_eq!(decide("command.inject", PermissionScope::Execute, Some("agent-a"), &p), Decision::Allowed);
        assert!(matches!(decide("command.inject", PermissionScope::Execute, Some("agent-b"), &p), Decision::RefusedOwner { .. }));
        assert!(matches!(decide("command.execute", PermissionScope::Execute, None, &p), Decision::RefusedOwner { .. }));
        // Rollback: check off → allowed (and still logged by the caller of decide).
        let off = Policy { check_owner: false, ..p.clone() };
        assert_eq!(decide("command.inject", PermissionScope::Execute, Some("agent-b"), &off), Decision::Allowed);
        // Scope is checked first even for the owner.
        assert!(matches!(decide("command.execute", PermissionScope::Control, Some("agent-a"), &p), Decision::RefusedScope { .. }));
    }

    // E-68: every attempt, allowed or refused, leaves a row with the caller.
    #[test]
    fn e68_gate_writes_a_row_per_attempt() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("use-log").join("s.jsonl");
        let p = policy(Some("agent-a"), path.clone());
        let mk = |from: &str| json!({"keys": [], "from": from});
        assert!(gate_session(json!(1), "command.inject", &mk("agent-a"), PermissionScope::Control, (Some(1000), Some(42)), "tl-s", None, &p).is_none());
        assert!(gate_session(json!(2), "command.inject", &mk("agent-b"), PermissionScope::Control, (Some(1000), Some(43)), "tl-s", None, &p).is_some());
        assert!(gate_session(json!(3), "command.execute", &mk("agent-a"), PermissionScope::Observe, (Some(1000), Some(44)), "tl-s", None, &p).is_some());
        let r = rows(&path);
        assert_eq!(r.len(), 3);
        assert_eq!(r[0]["decision"], "allowed");
        assert_eq!(r[0]["caller"]["from"], "agent-a");
        assert_eq!(r[0]["caller"]["pid"], 42);
        assert_eq!(r[0]["at"], "session");
        assert_eq!(r[0]["target"], "tl-s");
        assert_eq!(r[1]["decision"], "refused-owner");
        assert_eq!(r[1]["fcw"], "FCW-131");
        assert_eq!(r[2]["decision"], "refused-scope");
        assert_eq!(r[2]["scope"], "observe");
    }

    // E-169 / FCW-132: the row cannot be written → refused, with the reason.
    #[test]
    fn e169_unwritable_log_refuses() {
        let dir = tempfile::tempdir().unwrap();
        let blocker = dir.path().join("file");
        std::fs::write(&blocker, b"x").unwrap();
        // The parent of the log path is a regular file: create_dir_all fails.
        let p = policy(None, blocker.join("s.jsonl"));
        let resp = gate_session(json!(1), "command.inject", &json!({}), PermissionScope::Execute, (None, None), "tl-s", None, &p)
            .expect("refused");
        let v = serde_json::to_value(&resp).unwrap();
        assert_eq!(v["error"]["code"], control::error_code::USE_LOG_UNWRITABLE);
        assert_eq!(v["error"]["data"]["fcw"], "FCW-132");
        assert!(v["error"]["message"].as_str().unwrap().contains("use-log row could not be written"));
    }

    #[test]
    fn refusal_names_fcw_and_caller() {
        let d = Decision::RefusedOwner { owner: "a".into(), caller: None };
        let v = serde_json::to_value(refusal(json!(1), "command.inject", &d).unwrap()).unwrap();
        assert_eq!(v["error"]["code"], control::error_code::AUTH_DENIED);
        assert_eq!(v["error"]["data"]["fcw"], "FCW-131");
        assert!(v["error"]["message"].as_str().unwrap().contains("undeclared caller"));
        assert!(refusal(json!(1), "command.inject", &Decision::Allowed).is_none());
    }
}
